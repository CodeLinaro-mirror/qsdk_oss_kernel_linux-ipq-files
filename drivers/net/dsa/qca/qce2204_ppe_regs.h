/* Helper macro for multi-word register field modification */
#define QCE2204_FIELD_MODIFY(field, tbl_cfg, value) \
	do { \
		u32 *_cfg = (tbl_cfg); \
		u32 _val = *_cfg; \
		_val &= ~(field); \
		_val |= FIELD_PREP(field, value); \
		*_cfg = _val; \
	} while (0)

